"""Analytic fixture mothers for the pattern test-suite (documented as fixtures).

``synlab.mothers.api.create_mother`` is implemented by a different workstream; while it
is unavailable the pattern layer is tested against **analytic** chart fixtures built here:

* a closed lathe body (outer wall + rim + inner wall + inner base + foot) whose outer and
  inner walls are true cylinders, so ``s = z`` is the exact profile arc length and
  ``u = atan2(y,x)/(2*pi) mod 1`` is the exact periodic azimuth;
* the same body with independent charts for the outer wall, inner wall and the base/foot
  plane, so per-chart legal drawing boundaries are exercised.

The fixtures are real meshes (watertight, outward oriented, millimetres) and expose the
frozen chart contract (``x_period_mm``, ``meta["s_range_mm"]``, ``meta["uv_to_xyz"]``,
``meta["s_periodic"]``).  Tests that depend on them say so in their name/docstring.
"""

from __future__ import annotations

import math
from typing import Any, Callable

import numpy as np
import trimesh

from synlab.schemas.runtime import Chart, MotherGeometry

TWO_PI = 2.0 * math.pi

TAG_OUTER = 0
TAG_INNER = 1
TAG_RIM = 2
TAG_BASE = 3
TAG_FOOT = 4

TAG_NAMES = {TAG_OUTER: "outer_wall", TAG_INNER: "inner_wall", TAG_RIM: "rim",
             TAG_BASE: "base", TAG_FOOT: "foot"}


def lathe(profile: np.ndarray, tags: list[int], sections: int = 64) -> tuple[trimesh.Trimesh, np.ndarray]:
    """Revolve a closed ``(r, z)`` profile and return ``(mesh, face_tags)``.

    ``tags[i]`` labels the ring band generated by profile segment ``i``.
    """
    profile = np.asarray(profile, dtype=np.float64)
    n = profile.shape[0]
    vertices = []
    for k in range(sections):
        angle = TWO_PI * k / sections
        for r, z in profile:
            vertices.append([r * math.cos(angle), r * math.sin(angle), z])
    faces: list[list[int]] = []
    face_tags: list[int] = []
    for k in range(sections):
        k2 = (k + 1) % sections
        for i in range(n):
            i2 = (i + 1) % n
            a = k * n + i
            b = k * n + i2
            c = k2 * n + i2
            d = k2 * n + i
            faces.append([a, b, c])
            face_tags.append(int(tags[i]))
            faces.append([a, c, d])
            face_tags.append(int(tags[i]))
    mesh = trimesh.Trimesh(vertices=np.asarray(vertices), faces=np.asarray(faces), process=True)
    keep = np.asarray(mesh.nondegenerate_faces())
    mesh.update_faces(keep)
    mesh.remove_unreferenced_vertices()
    tags_arr = np.asarray(face_tags, dtype=np.int64)[keep]
    if float(mesh.volume) < 0:
        mesh.invert()
    mesh.process(validate=False)
    return mesh, tags_arr


def cylinder_profile(*, radius_mm: float, height_mm: float, wall_mm: float,
                     base_mm: float) -> tuple[np.ndarray, list[int]]:
    """Closed profile of a cup: outer wall, rim, inner wall, inner base, foot."""
    r_out = float(radius_mm)
    r_in = r_out - float(wall_mm)
    h = float(height_mm)
    b = float(base_mm)
    profile = [
        (0.0, 0.0),          # axis, outer bottom centre
        (r_out, 0.0),        # outer bottom edge
        (r_out, h),          # outer wall top
        (r_in, h),           # rim
        (r_in, b),           # inner wall bottom
        (0.0, b),            # inner base centre
    ]
    # segment i goes profile[i] -> profile[i+1] (closing back to profile[0])
    tags = [TAG_FOOT, TAG_OUTER, TAG_RIM, TAG_INNER, TAG_BASE, TAG_FOOT]
    return np.asarray(profile, dtype=np.float64), tags


def make_cylinder_mother(*, radius_mm: float = 40.0, height_mm: float = 55.0,
                         wall_mm: float = 4.0, base_mm: float = 5.0, sections: int = 96,
                         mother_id: str = "fixture_cylinder") -> MotherGeometry:
    profile, tags = cylinder_profile(radius_mm=radius_mm, height_mm=height_mm,
                                     wall_mm=wall_mm, base_mm=base_mm)
    mesh, face_tags = lathe(profile, tags, sections=sections)
    r_in = radius_mm - wall_mm

    def outer_to_uv(points: np.ndarray) -> np.ndarray:
        pts = np.asarray(points, dtype=np.float64)
        u = np.mod(np.arctan2(pts[:, 1], pts[:, 0]) / TWO_PI, 1.0)
        return np.stack([u, pts[:, 2]], axis=1)

    def inner_to_uv(points: np.ndarray) -> np.ndarray:
        pts = np.asarray(points, dtype=np.float64)
        u = np.mod(np.arctan2(pts[:, 1], pts[:, 0]) / TWO_PI, 1.0)
        return np.stack([u, pts[:, 2]], axis=1)

    def planar_to_uv(points: np.ndarray, z_plane: float) -> np.ndarray:
        pts = np.asarray(points, dtype=np.float64)
        return np.stack([pts[:, 0], pts[:, 1]], axis=1)

    def outer_xyz(uv: np.ndarray) -> np.ndarray:
        uv = np.asarray(uv, dtype=np.float64)
        angle = TWO_PI * uv[:, 0]
        return np.stack([radius_mm * np.cos(angle), radius_mm * np.sin(angle), uv[:, 1]], axis=1)

    def inner_xyz(uv: np.ndarray) -> np.ndarray:
        uv = np.asarray(uv, dtype=np.float64)
        angle = TWO_PI * uv[:, 0]
        return np.stack([r_in * np.cos(angle), r_in * np.sin(angle), uv[:, 1]], axis=1)

    charts = [
        Chart(name="outer_revolve", surface_tags=(TAG_OUTER,), kind="revolve", u_periodic=True,
              x_period_mm=TWO_PI * radius_mm, area_mm2=TWO_PI * radius_mm * height_mm,
              to_uv=outer_to_uv,
              meta={"s_range_mm": [base_mm, height_mm], "s_periodic": False,
                    "uv_to_xyz": outer_xyz,
                    "s_definition": "true profile arc length; the outer wall is a cylinder so "
                                    "s equals z exactly",
                    "fixture": "analytic cylinder chart (tests/a12/patterns)"}),
        Chart(name="inner_revolve", surface_tags=(TAG_INNER,), kind="revolve", u_periodic=True,
              x_period_mm=TWO_PI * r_in, area_mm2=TWO_PI * r_in * (height_mm - base_mm),
              to_uv=inner_to_uv,
              meta={"s_range_mm": [base_mm, height_mm], "s_periodic": False,
                    "uv_to_xyz": inner_xyz,
                    "s_definition": "true profile arc length on the inner cylinder",
                    "fixture": "analytic cylinder chart (tests/a12/patterns)"}),
        Chart(name="base_plane", surface_tags=(TAG_BASE, TAG_FOOT), kind="planar",
              u_periodic=False, x_period_mm=None,
              area_mm2=math.pi * radius_mm ** 2,
              to_uv=lambda pts: planar_to_uv(pts, 0.0),
              meta={"s_range_mm": [-radius_mm, radius_mm], "s_periodic": False,
                    "s_definition": "planar chart: column 0/1 are already millimetres",
                    "fixture": "analytic plane chart (tests/a12/patterns)"}),
    ]
    mother = MotherGeometry(mesh=mesh, face_surface_tag=face_tags, surface_tag_names=dict(TAG_NAMES),
                            charts=charts, vessel_id="V01", material_id="M01",
                            params={"wall_thickness_mm": wall_mm, "height_mm": height_mm,
                                    "radius_mm": radius_mm},
                            mother_id=mother_id,
                            meta={"min_wall_thickness_mm": wall_mm,
                                  "fixture": "analytic lathe fixture",
                                  "units": "mm"})
    mesh.metadata = dict(mesh.metadata or {})
    mesh.metadata["face_attr_arrays"] = {"surface_tag": face_tags}
    return mother


def make_thin_wall_mother(*, wall_mm: float = 1.6, radius_mm: float = 35.0,
                          height_mm: float = 45.0, sections: int = 64) -> MotherGeometry:
    """Same body with a thin wall, used for the engraving wall-thickness guard."""
    return make_cylinder_mother(radius_mm=radius_mm, height_mm=height_mm, wall_mm=wall_mm,
                                base_mm=2.5, sections=sections, mother_id="fixture_thin_wall")


def make_small_mother(*, sections: int = 48) -> MotherGeometry:
    """Small fixture for fast loops over the 16 families."""
    return make_cylinder_mother(radius_mm=22.0, height_mm=32.0, wall_mm=3.0, base_mm=4.0,
                                sections=sections, mother_id="fixture_small")


def outer_points(mother: MotherGeometry, n: int, rng: np.random.Generator) -> np.ndarray:
    """Random points on the fixture body (world millimetres, area weighted)."""
    points = mother.mesh.sample(n, seed=rng)
    return np.asarray(points, dtype=np.float64)
